#!/usr/bin/env python3
"""Run the sound experiments against the real IPC firmware (via ipc8049_sim.py)
and print the results as Markdown.

usage: ipc8049_experiments.py LISTING_OR_ROM > findings.md
"""

import sys

from ipc8049_sim import CYCLE_US, Link, MCS48, load_rom

TICK_US = CYCLE_US * 32


def run(rom, p1, p2, interval, duration, step, wrap, rnd, fz, ms, prescaler="strt"):
    link = Link()
    cpu = MCS48(rom, link, prescaler)
    cpu.run_cycles(int(60000 / CYCLE_US))                       # let the firmware settle after reset
    t0, r0, e0 = cpu.cycles, len(cpu.reloads), len(cpu.speaker)
    link.send_command(0xA, [p1, p2, interval & 0xFF, interval >> 8, duration & 0xFF, duration >> 8,
                            ((step & 0xF) << 4) | (wrap & 0xF), ((rnd & 0xF) << 4) | (fz & 0xF)])
    cpu.run_cycles(int(ms * 1000 / CYCLE_US))
    reloads = [((c - t0) * CYCLE_US, px, cnt) for c, px, cnt in cpu.reloads[r0:]]
    edges = [((c - t0) * CYCLE_US, lvl) for c, lvl in cpu.speaker[e0:]]
    off = None
    if cpu.sound_off_cycle is not None and cpu.sound_off_cycle >= t0:
        off = (cpu.sound_off_cycle - t0) * CYCLE_US
    return reloads, edges, off


def half_period(edges):
    gaps = [edges[i + 1][0] - edges[i][0] for i in range(len(edges) - 1)]
    gaps = gaps[2:] if len(gaps) > 6 else gaps
    return sorted(gaps)[len(gaps) // 2]


def fit_hz(n):
    """Published empirical fit (QBITS article), in terms of the IPC pitch byte N (0 means 256)."""
    return 11336.256 / ((n or 256) + 7.634)


def collapse(reloads):
    out = []
    for _, px, _ in reloads:
        if out and out[-1][0] == px:
            out[-1][1] += 1
        else:
            out.append([px, 1])
    return out


def main(path):
    rom = load_rom(path)
    print("# IPC sound: results from running the real firmware\n")
    print("Generated by `ipc8049_experiments.py` using `ipc8049_sim.py` (an MCS-48 interpreter running the IPC "
          "firmware; the ZX8302 link is replaced by a nibble queue). Assumes an 11.000 MHz crystal, 15 clocks "
          "per machine cycle, timer prescaler /32, prescaler cleared by STRT T.\n")

    print("## 1. Pitch byte versus frequency (duration 0, no sweep)\n")
    print("| IPC byte N | BEEP pitch | simulated Hz | published fit Hz | sim/fit | overhead (ticks) |")
    print("|---|---|---|---|---|---|")
    for n in (1, 2, 5, 11, 21, 51, 101, 201, 0):
        _, edges, _ = run(rom, n, n, 0, 0, 0, 0, 0, 0, 400 if n in (0, 201) else 120)
        hp = half_period(edges)
        hz = 1e6 / (2 * hp)
        print(f"| {n} | {(n - 1) % 256} | {hz:.1f} | {fit_hz(n):.1f} | {hz / fit_hz(n):.3f} | {hp / TICK_US - (n or 256):.2f} |")

    print("\n## 2. A non-zero duration lowers the pitch (extra work in every timer interrupt)\n")
    print("| IPC byte N | duration 0 (Hz) | duration 1000 (Hz) |")
    print("|---|---|---|")
    for n in (1, 11, 51):
        row = []
        for d in (0, 1000):
            _, edges, _ = run(rom, n, n, 0, d, 0, 0, 0, 0, 150)
            row.append(1e6 / (2 * half_period(edges)))
        print(f"| {n} | {row[0]:.1f} | {row[1]:.1f} |")

    print("\n## 3. How long a timed tone lasts (first edge to the sound-on flag clearing)\n")
    print("| IPC byte N | duration 100 | duration 1000 |")
    print("|---|---|---|")
    for n in (1, 11, 51, 0):
        cells = []
        for d in (100, 1000):
            _, edges, off = run(rom, n, n, 0, d, 0, 0, 0, 0, 900)
            span = (off - edges[0][0]) if off and edges else None
            cells.append("never" if span is None else f"{span / 1000:.2f} ms ({span / d:.1f} us/unit)")
        print(f"| {n} | {cells[0]} | {cells[1]} |")

    print("\n## 4. Large (negative) durations: unsigned 16-bit compare against a wrapping accumulator\n")
    print("| IPC byte N | duration | result |")
    print("|---|---|---|")
    for n, d, ms in ((1, 0x7FFF, 3000), (1, 0x8000, 3000), (11, 0xFFFF, 6500), (51, 0xFFFF, 6500)):
        _, edges, off = run(rom, n, n, 0, d, 0, 0, 0, 0, ms)
        res = f"ended after {(off - edges[0][0]) / 1e6:.2f} s" if off else f"still sounding after {ms / 1000:.1f} s"
        print(f"| {n} | 0x{d:04X} | {res} |")

    print("\n## 5. Sweeps: sequence of pitch values (value x half-cycles at that value)\n")
    cases = [
        ("basic sweep, wrap 0 (bounce)", 20, 30, 1000, 4, 0, 700),
        ("equal pitches, step non-zero", 20, 20, 1000, 4, 0, 500),
        ("pitch2 below pitch1", 20, 10, 1000, 4, 0, 500),
        ("negative step", 20, 30, 1000, -4, 0, 700),
        ("wrap 1", 20, 30, 1000, 4, 1, 1300),
        ("wrap 2", 20, 30, 1000, 4, 2, 1700),
        ("wrap 15", 20, 30, 1000, 4, 15, 1300),
        ("interval 0, step non-zero", 20, 60, 0, 4, 0, 60),
        ("step 0, interval non-zero", 20, 30, 1000, 0, 0, 300),
    ]
    for title, p1, p2, iv, st, wr, ms in cases:
        reloads, _, _ = run(rom, p1, p2, iv, 0, st, wr, 0, 0, ms)
        seq = collapse(reloads)[:16]
        print(f"**{title}** (pitch1={p1}, pitch2={p2}, interval={iv}, step={st}, wrap={wr})\n")
        print("`" + " ".join(f"{px}x{k}" for px, k in seq) + "`\n")

    print("## 6. Sensitivity to the prescaler assumption (N=1, duration 0)\n")
    print("| prescaler cleared by | simulated Hz |")
    print("|---|---|")
    for mode in ("strt", "mov_t", "never"):
        _, edges, _ = run(rom, 1, 1, 0, 0, 0, 0, 0, 0, 120, prescaler=mode)
        print(f"| {mode} | {1e6 / (2 * half_period(edges)):.1f} |")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
