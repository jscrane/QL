#!/usr/bin/env python3
"""Generate ipc_sound_vectors.h: golden vectors for the QL sound model, taken from
the real IPC firmware running in ipc8049_sim.py.

Each vector is a set of initiate-sound parameters (wire values, as SoundAdapter::Params
holds them) plus what the firmware did: the sequence of "runs" (consecutive half-cycles at
one pitch value) with their durations, and when the sound-on flag cleared.

usage: gen_sound_vectors.py LISTING_OR_ROM > ipc_sound_vectors.h
"""

import sys

from ipc8049_sim import CYCLE_US, Link, MCS48, load_rom

# name, pitch1, pitch2, interval, duration, step, wrap, window_ms
VECTORS = [
    ("steady_untimed",              11, 11,    0,      0,  0,  0,  150),
    ("steady_timed_1000",           11, 11,    0,   1000,  0,  0,  150),
    ("steady_timed_1000_lowest",     0,  0,    0,   1000,  0,  0,  300),
    ("sweep_bounce",                20, 30, 1000,      0,  4,  0,  700),
    ("sweep_equal_pitches",         20, 20, 1000,      0,  4,  0,  500),
    ("sweep_pitch2_below_pitch1",   20, 10, 1000,      0,  4,  0,  500),
    ("sweep_negative_step",         20, 30, 1000,      0, -4,  0,  700),
    ("sweep_wrap_1",                20, 30, 1000,      0,  4,  1, 1300),
    ("sweep_wrap_2",                20, 30, 1000,      0,  4,  2, 1700),
    ("sweep_wrap_15",               20, 30, 1000,      0,  4, 15, 1300),
    ("sweep_interval_zero",         20, 60,    0,      0,  4,  0,   60),
    ("sweep_step_zero",             20, 30, 1000,      0,  0,  0,  300),
    ("sweep_timed",                 20, 60,  300,   3000,  2,  0,  400),
    ("duration_max_pitch_11",       11, 11,    0, 0xFFFF,  0,  0, 4500),
    ("duration_max_pitch_51",       51, 51,    0, 0xFFFF,  0,  0, 6500),
]


def simulate(rom, p1, p2, interval, duration, step, wrap, window_ms):
    link = Link()
    cpu = MCS48(rom, link)
    cpu.run_cycles(int(60000 / CYCLE_US))
    t0, r0 = cpu.cycles, len(cpu.reloads)
    link.send_command(0xA, [p1, p2, interval & 0xFF, interval >> 8, duration & 0xFF, duration >> 8,
                            ((step & 0xF) << 4) | (wrap & 0xF), 0])
    cpu.run_cycles(int(window_ms * 1000 / CYCLE_US))
    reloads = [(c, px) for c, px, _ in cpu.reloads[r0:]]
    if len(reloads) < 2:
        raise RuntimeError("no sound produced")
    origin = reloads[0][0]
    runs = []                                   # [pitch, half_cycles, start_cycle]
    for c, px in reloads:
        if runs and runs[-1][0] == px:
            runs[-1][1] += 1
        else:
            runs.append([px, 1, c])
    out = []
    for i, (px, n, start) in enumerate(runs):
        last = i == len(runs) - 1
        end = cpu.cycles if last else runs[i + 1][2]
        out.append((px, n, round((end - start) * CYCLE_US), not last))
    ends = 0
    if cpu.sound_off_cycle is not None and cpu.sound_off_cycle >= origin:
        ends = round((cpu.sound_off_cycle - origin) * CYCLE_US)
    return out, ends, round((cpu.cycles - origin) * CYCLE_US)


def main(path):
    rom = load_rom(path)
    print("// Generated by gen_sound_vectors.py from ipc8049_sim.py (the real IPC firmware). Do not edit.")
    print("// Times are microseconds from the first sound timer reload after the command.")
    print("// A run is consecutive half-cycles at one pitch value; the last run in each vector is cut off")
    print("// by the end of the simulated window (complete == false), so only its pitch and half-cycle")
    print("// length are meaningful.")
    print("#pragma once\n#include <cstdint>\n")
    print("struct SoundRun { uint8_t pitch; uint16_t half_cycles; uint32_t us; bool complete; };")
    print("struct SoundVector {")
    print("\tconst char *name;")
    print("\tuint8_t pitch1, pitch2;          // IPC wire bytes (BEEP pitch + 1)")
    print("\tuint16_t interval, duration;")
    print("\tint8_t step;")
    print("\tuint8_t wrap;")
    print("\tuint32_t ends_us;                // when the sound-on flag cleared; 0 = still on at the end of the window")
    print("\tuint32_t window_us;")
    print("\tconst SoundRun *runs;")
    print("\tunsigned nruns;")
    print("};\n")
    entries = []
    for name, p1, p2, iv, dur, st, wr, ms in VECTORS:
        runs, ends, window = simulate(rom, p1, p2, iv, dur, st, wr, ms)
        runs = runs[:48]
        print(f"static const SoundRun {name}_runs[] = {{")
        for px, n, us, complete in runs:
            print(f"\t{{ {px}, {n}, {us}, {'true' if complete else 'false'} }},")
        print("};")
        entries.append(f'\t{{ "{name}", {p1}, {p2}, {iv}, {dur}, {st}, {wr}, {ends}, {window}, '
                       f'{name}_runs, {len(runs)} }},')
    print("\nstatic const SoundVector sound_vectors[] = {")
    print("\n".join(entries))
    print("};")
    print(f"static const unsigned n_sound_vectors = {len(entries)};")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
