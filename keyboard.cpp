bool Keyboard::available() {

	// leave room for the key-up event...
	if (_avail >= (sizeof(_buf) - 1))
		return true;

	while (_serial.available()) {
		uint8_t key = _serial.read();
		uint16_t code = pgm_read_word(&keycodes[key]);
		DBG_EMU("%d %02x %04x", _tail, key, code);
		if (code == 0)
			continue;

		_buf[_tail] = code;
		if (++_tail == sizeof(_buf)) _tail = 0;
		if (++_avail == sizeof(_buf)) break;

		_buf[_tail] = code | 0x80;
		if (++_tail == sizeof(_buf)) _tail = 0;
		if (++_avail == sizeof(_buf)) break;
	}
	return _avail;
}

uint16_t Keyboard::read() {

	if (_avail == 0)
		return 0xffff;

	_avail--;
	uint16_t code = _buf[_head];
	if (++_head == sizeof(_buf)) _head = 0;
	return code;
}
